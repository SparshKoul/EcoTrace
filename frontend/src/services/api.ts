export async function submitReport(submission: ReportSubmission): Promise<ReportReceipt> {
  if (USE_MOCK_API) {
    await wait(400);
    const report_id = `local-${Date.now().toString(36)}`;
    mockActivity = [
      {
        id: report_id,
        type: submission.type,
        status: 'PROCESSING',
        location: submission.location,
        createdAt: new Date().toISOString(),
        detail: submission.note || 'Submitted for AI verification',
      },
      ...mockActivity,
    ];
    return { report_id, status: 'PROCESSING' };
  }

  const firstPhoto = submission.media[0] ? await blobToDataUrl(submission.media[0]) : '';
  const response = await fetch(`${API_BASE_URL}/api/reports`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', ...authHeaders() },
    body: JSON.stringify({
      photoUrl: firstPhoto || 'https://example.com/no-photo.jpg',
      wasteType: submission.type,
      latitude: submission.location.lat,
      longitude: submission.location.lng,
    }),
  });
  const data = await response.json().catch(() => ({})) as {
    report?: { id?: string; photo_url?: string; sanitized_photo_url?: string };
    siteId?: string;
    clustered?: boolean;
    aiVerification?: any;
    error?: string;
    message?: string;
    details?: any;
  };

  // If rejected by AI vision judge, return receipt as REJECTED with full judge statement
  if (response.status === 422 && (data.error === 'AI_VERIFICATION_REJECTED' || data.details)) {
    return {
      report_id: `rejected-${Date.now()}`,
      status: 'REJECTED',
      aiVerification: {
        status: 'REJECTED',
        wasteCategory: submission.type,
        confidence: data.details?.confidence ?? 0.85,
        auditSummary: data.details?.auditSummary ?? data.message,
        rejectionReason: data.details?.rejectionReason ?? data.message ?? 'Image was evaluated and not recognized as outdoor waste.',
        detectedClasses: data.details?.detectedClasses ?? [],
      },
    };
  }

  if (!response.ok) throw new Error(data.message ?? data.error ?? 'The report could not be submitted.');

  const ai = data.aiVerification;
  return {
    report_id: String(data.report?.id ?? `local-${Date.now()}`),
    status: (ai?.status === 'VERIFIED' || ai?.status === 'ACCEPTED') ? 'VERIFIED' : (ai?.status === 'REJECTED' ? 'REJECTED' : 'REVIEW_REQUIRED'),
    site_id: data.siteId,
    aiVerification: ai ? {
      status: ai.status,
      wasteCategory: ai.waste_category || ai.category || submission.type,
      confidence: ai.confidence,
      auditSummary: ai.audit_summary,
      rejectionReason: ai.rejection_reason,
      detectedClasses: ai.detected_classes,
      siteAction: data.clustered ? 'merged' : 'created',
      siteId: data.siteId,
      evidenceUrl: data.report?.photo_url || data.report?.sanitized_photo_url,
    } : undefined,
  };
}

export async function fetchComplaint(siteId: string): Promise<ComplaintLetter> {
  if (USE_MOCK_API) {
    await wait(150);
    const site = MOCK_SITES.find((item) => item.id === siteId) ?? MOCK_SITES[0]!;
    const citations = VERIFIED_CITATIONS.map((item) => `"${item.text}" — SWM Rules 2026, rule ${item.clause}.`);
    const body = [
      `To,\nThe Municipal Commissioner,\n${site.boundary.ulb ?? 'Urban Local Body'}`,
      `CC: MLA — ${site.boundary.mla ?? 'Constituency office'}; MP — ${site.boundary.mp ?? 'Constituency office'}`,
      '',
      `Subject: Unaddressed solid waste accumulation at a verified site in ${site.boundary.mla ?? 'your jurisdiction'}`,
      '',
      `Respected Sir/Madam,`,
      `A verified citizen report records solid waste accumulation at latitude ${site.lat.toFixed(5)}, longitude ${site.lng.toFixed(5)} within your jurisdiction. The site currently holds ${site.reportCount} reports from ${site.reporterCount} distinct reporters and remains ${site.status}.`,
      '',
      ...citations,
      '',
      `We request that the site be mapped, assessed and remediated, and that the preventive measures above be put in place. This letter is a citizen draft for review and has not been sent automatically.`,
      '',
      `Yours faithfully,\nA concerned citizen (via EcoTrace)`,
    ].join('\n');
    return {
      siteId: site.id,
      recipient: site.boundary.ulb ?? 'Urban Local Body',
      cc: [site.boundary.mla ?? '', site.boundary.mp ?? ''].filter(Boolean),
      subject: 'Unaddressed solid waste accumulation — verified EcoTrace report',
      body,
      citations: VERIFIED_CITATIONS.map((item) => item.text),
      generatedAt: new Date().toISOString(),
    };
  }

  const response = await fetch(
    `${API_BASE_URL}/api/letters/site/${encodeURIComponent(siteId)}`,
    { headers: authHeaders() },
  );
  if (!response.ok) throw new Error('The complaint letter could not be prepared.');
  const letter = await response.json() as {
    letter_id: string; site_id: string; to: string; cc: string[]; subject: string;
    body: string; citations: { quote: string }[]; created_at: string;
  };
  return {
    siteId: letter.site_id,
    recipient: letter.to,
    cc: letter.cc,
    subject: letter.subject,
    body: letter.body,
    citations: letter.citations.map((citation) => citation.quote),
    generatedAt: letter.created_at,
  };
}


export async function fetchSites(): Promise<Site[]> {
  if (USE_MOCK_API) {
    await wait(150);
    return [...MOCK_SITES];
  }
  const response = await fetch(`${API_BASE_URL}/api/v1/sites`);
  if (!response.ok) throw new Error('Could not load verified dump sites.');
  return (await response.json()) as Site[];
}

